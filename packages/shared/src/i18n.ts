export function translateText(value: string, language: AppLanguage): string {
  if (language !== "ar") return value;
  const trimmed = value.trim();
  const translation = arabic[trimmed];
  if (!translation) {
    const choice = trimmed.match(/^Choice (\d+)$/);
    if (choice) return `الخيار ${choice[1].replace(/[0-9]/g, (digit) => "٠١٢٣٤٥٦٧٨٩"[Number(digit)])}`;
    const votes = trimmed.match(/^(\d+) votes?$/);
    if (votes) return `${votes[1]} ${votes[1] === "1" ? "صوت" : "أصوات"}`;
    const reportCount = trimmed.match(/^You have (\d+) active reports?$/);
    if (reportCount) return `لديك ${reportCount[1]} ${reportCount[1] === "1" ? "بلاغ نشط" : "بلاغات نشطة"}`;
    const activeCount = trimmed.match(/^(\d+) active$/);
    if (activeCount) return `${activeCount[1]} نشط`;
    const greeting = trimmed.match(/^Hi, (.+)$/);
    if (greeting) return `مرحبًا، ${greeting[1]}`;
    return value;
  }
  const leading = value.match(/^\s*/)?.[0] ?? "";
  const trailing = value.match(/\s*$/)?.[0] ?? "";
  return `${leading}${translation}${trailing}`;
}
